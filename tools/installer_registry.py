"""
Generates installer/extensions.iss: the per-extension registry lines of the installer.

The list of extensions comes from core/media_types.py, so the Open dialog and the
Windows file association can never disagree. Run via tools/build_release.py (or directly).

Registration is "Open with" only: Pane appears in the right-click "Open with" list and in
Settings > Default apps, but the installer never takes over a user's current default.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from core.media_types import VIDEO_EXTENSIONS  # noqa: E402

OUT = ROOT / "installer" / "extensions.iss"
PROGID = "Pane.Video"


def build_lines() -> str:
    lines = [
        "; GENERATED by tools/installer_registry.py from core/media_types.py - do not edit by hand.",
        "",
    ]
    for ext in VIDEO_EXTENSIONS:
        # shows Pane in the 'Open with' list for this extension
        lines.append(
            f'Root: HKA; Subkey: "Software\\Classes\\.{ext}\\OpenWithProgids"; ValueType: string; '
            f'ValueName: "{PROGID}"; ValueData: ""; Flags: uninsdeletevalue; Tasks: fileassoc')
        # lists the extension under Pane's capabilities (Settings > Default apps)
        lines.append(
            f'Root: HKA; Subkey: "Software\\Pane\\Capabilities\\FileAssociations"; ValueType: string; '
            f'ValueName: ".{ext}"; ValueData: "{PROGID}"; Flags: uninsdeletevalue; Tasks: fileassoc')
        lines.append(
            f'Root: HKA; Subkey: "Software\\Classes\\Applications\\Pane.exe\\SupportedTypes"; ValueType: string; '
            f'ValueName: ".{ext}"; ValueData: ""; Flags: uninsdeletevalue; Tasks: fileassoc')
    return "\n".join(lines) + "\n"


def write() -> Path:
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(build_lines(), encoding="utf-8")
    return OUT


if __name__ == "__main__":
    print("wrote", write())
